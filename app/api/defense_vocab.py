def vocab() -> dict:
    """The same words as lists the pages draw from."""
    pair = lambda d: [{"key": k, "icon": v[0], "text": v[1], "hint": v[2] if len(v) > 2 else ""} for k, v in d.items()]  # noqa: E731
    word = lambda d: [{"key": k, "text": v} for k, v in d.items()]  # noqa: E731
    return {
        "scale": SCALE, "kinds": word(KINDS), "results": pair(RESULTS), "answers": word(ANSWERS), "facts": word(FACTS), "marks": pair(MARKS),
        "rates": [{"key": k, "text": title, "steps": [{"text": t, "hint": h} for t, h in steps]} for k, (title, steps) in RATES.items()],
        "tags": [{"key": k, "text": t, "hint": h} for k, (t, h) in TAGS.items()], "remark_kinds": pair(REMARK_KINDS), "paid": list(PAID),
        "replies": word(REPLIES), "linked": list(LINKED), "checks": word(CHECKS), "efforts": [{"coin": c, "text": t} for c, t in EFFORTS],
    }
